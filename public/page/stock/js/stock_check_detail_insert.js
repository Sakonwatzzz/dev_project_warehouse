  function createNewStockSession() {
    if (isProcessing) {
      console.warn("createNewStockSession skipped due to isProcessing"); // Log ที่เห็น
      return;
    }
    isProcessing = true;
    console.log("Starting createNewStockSession, isProcessing:", isProcessing); // Debug

    let stockDate = setStockDate();
    if (
      !stockDate ||
      !luxon.DateTime.fromFormat(stockDate, "yyyy-MM-dd HH:mm:ss").isValid
    ) {
      console.error("Invalid stock date:", stockDate);
      Toast.fire({
        icon: "error",
        title: "รูปแบบวันที่ไม่ถูกต้อง",
      });
      isProcessing = false;
      return;
    }
    const warehouse_id = $("#warehouse_select").val();
    // const personnel_id = getValue("#personnel_id", "1");

    console.log("DOM state:", { warehouse_id}); // Debug //, personnel_id 
    if (!warehouse_id ) { //|| !personnel_id
      console.error("Missing warehouse_id ", { //or personnel_id:
        warehouse_id,
        //personnel_id,
      });
      Toast.fire({
        icon: "error",
        title: "กรุณาเลือกคลังหรือระบุผู้ใช้",
      });
      isProcessing = false;
      return;
    }

    console.log("Creating new stock session with data:", {
      stockDate,
      warehouse_id,
     // personnel_id,
    }); // Debug
    $.ajax({
      url: "page/stock/api/insert_new_stock.php",
      type: "POST",
      data: {
        action: "insert_new_stock",
        stock_date: stockDate,
      //  personnel_id: personnel_id,
        check_status_id: "1",
        warehouse_id: warehouse_id,
      },
      dataType: "json",
      headers: { "X-Requested-With": "XMLHttpRequest" },
      cache: false,
      success: function (response) {
        console.log("insert_new_stock.php response:", response); // Debug
        isProcessing = false;
        if (response.status === "success" && response.stock_id) {
          currentStockId = response.stock_id;
          $("#current_stock_id").val(currentStockId);
          startNewStockCheck();
          loadStockSessions();
          Toast.fire({
            icon: "success",
            title: `เริ่มเซสชันตรวจสอบสต๊อก (${currentStockId}) เรียบร้อย`,
          });
          console.log(
            "Redirecting to:",
            `?page=stock_insert&stock_id=${currentStockId}`
          ); // Debug
          window.location.assign(
            `?page=stock_insert&stock_id=${currentStockId}`
          );
        } else if (response.status === "warning") {
          console.warn("insert_new_stock.php warning:", response.message);
          Toast.fire({
            icon: "warning",
            title: response.message,
          });
        } else {
          console.error("createNewStockSession failed:", response.message);
          Toast.fire({
            icon: "error",
            title: response.message || "ไม่สามารถสร้างเซสชันใหม่ได้",
          });
        }
      },
      error: function (xhr, status, error) {
        console.error("insert_new_stock.php error:", xhr.responseText);
        Toast.fire({
          icon: "error",
          title: "เกิดข้อผิดพลาดในการเริ่มเซสชันใหม่: " + error,
        });
        isProcessing = false;
      },
    });
  }

